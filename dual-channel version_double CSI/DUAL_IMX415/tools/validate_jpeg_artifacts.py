"""Exercise Python DJP2 reconstruction with real RTL-generated JPEG payloads.

The envelope here is generated by software. The separate header RTL test
checks the hardware-generated envelope; do not call these live DMA captures.
"""
import argparse,json,sys
from pathlib import Path
import numpy as np
from PIL import Image
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'rk'))
from dual_csi_protocol import HEADER,parse_packet,Assembler,decode_frame

def main():
    p=argparse.ArgumentParser();p.add_argument('--pipeline',action='store_true');a=p.parse_args()
    prefix='pipeline_' if a.pipeline else ''
    out=ROOT/'build'/('pipeline_reconstructed' if a.pipeline else 'jpeg_reconstructed')
    out.mkdir(exist_ok=True)
    assembler=Assembler();report=[]
    for cam in (0,1):
        tiles=[]
        for tile in (2,0,1):
            payload=(ROOT/'build'/f'{prefix}cam_{cam}_tile_{tile}.jpg').read_bytes()
            mode=(1 if cam==0 else 3) if a.pipeline else 0
            envelope=HEADER.pack(b'DJP2',2,32,1,cam,tile,mode,85,1920,1080,360,8,1,1,123+cam)
            packet=envelope+payload
            (out/f'cam_{cam}_tile_{tile}.djp').write_bytes(packet)
            parsed=parse_packet(packet,tile+1)
            tiles.append(parsed)
            group=assembler.push(parsed)
            if group:
                image=decode_frame(group);image.load()
                if image.size!=(1920,1080):raise ValueError('bad reconstructed geometry')
                image.save(out/f'camera_{cam}.png')
                record={'camera':cam,'size':list(image.size),'mode':mode,'quality':85,
                        'payload_bytes':sum(len(t.jpeg) for t in group)}
                if not a.pipeline:
                    y,x=np.indices((1080,1920),dtype=np.uint32)
                    h=((x+1)*np.uint32(0x045d9f3b)) ^ ((y+13)*np.uint32(0x119de1f3))
                    h=h^(h>>16)
                    reference=90+cam*30+((x//64+y//64)%6)*5+(h&15)
                    crack=(x%317==53)|(x%317==54)|((x+y//3)%491==75)
                    reference=reference.astype(np.int16)-crack.astype(np.int16)*48
                    raster=np.asarray(image).astype(np.int16)
                    mae=float(np.abs(raster-reference).mean())
                    naive=np.concatenate([np.asarray(Image.open(__import__('io').BytesIO(t.jpeg))) for t in group]).astype(np.int16)
                    wrong_mae=float(np.abs(naive-reference).mean())
                    record.update(mae_against_input=mae,mae_if_incorrect_vertical_stacking=wrong_mae)
                    if mae>=8 or mae>=wrong_mae:raise ValueError('JPEG corruption or stripe order mismatch')
                report.append(record)
    if len(report)!=2 or assembler.pending:raise ValueError('incomplete cameras')
    result={'source':'RTL simulation JPEG, software DJP2 envelope, not board capture','frames':report}
    (out/'report.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
    print(json.dumps(result,indent=2))

if __name__=='__main__':main()
