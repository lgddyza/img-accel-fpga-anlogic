#ifndef RK_FONT5X7_H
#define RK_FONT5X7_H

#include <string.h>

/* Five-column, seven-row bitmap font shared by the box and status OSDs. */
static void rk_glyph5x7(char c, unsigned char rows[7]) {
    static const unsigned char letters[26][7] = {
        {14,17,17,31,17,17,17}, {30,17,17,30,17,17,30},
        {14,17,16,16,16,17,14}, {30,17,17,17,17,17,30},
        {31,16,16,30,16,16,31}, {31,16,16,30,16,16,16},
        {14,17,16,23,17,17,14}, {17,17,17,31,17,17,17},
        {31,4,4,4,4,4,31}, {7,2,2,2,18,18,12},
        {17,18,20,24,20,18,17}, {16,16,16,16,16,16,31},
        {17,27,21,21,17,17,17}, {17,25,21,19,17,17,17},
        {14,17,17,17,17,17,14}, {30,17,17,30,16,16,16},
        {14,17,17,17,21,18,13}, {30,17,17,30,20,18,17},
        {15,16,16,14,1,1,30}, {31,4,4,4,4,4,4},
        {17,17,17,17,17,17,14}, {17,17,17,17,17,10,4},
        {17,17,17,21,21,21,10}, {17,17,10,4,10,17,17},
        {17,17,10,4,4,4,4}, {31,1,2,4,8,16,31}
    };
    static const unsigned char digits[10][7] = {
        {14,17,19,21,25,17,14}, {4,12,4,4,4,4,14},
        {14,17,1,2,4,8,31}, {30,1,1,14,1,1,30},
        {2,6,10,18,31,2,2}, {31,16,16,30,1,1,30},
        {14,16,16,30,17,17,14}, {31,1,2,4,8,8,8},
        {14,17,17,14,17,17,14}, {14,17,17,15,1,1,14}
    };
    static const unsigned char colon[7] = {0,4,4,0,4,4,0};
    static const unsigned char dot[7] = {0,0,0,0,0,4,4};
    static const unsigned char plus[7] = {0,4,4,31,4,4,0};
    if(c >= 'a' && c <= 'z') c -= 'a' - 'A';
    if(c >= 'A' && c <= 'Z') memcpy(rows, letters[c-'A'], 7);
    else if(c >= '0' && c <= '9') memcpy(rows, digits[c-'0'], 7);
    else if(c == ':') memcpy(rows, colon, 7);
    else if(c == '.') memcpy(rows, dot, 7);
    else if(c == '+') memcpy(rows, plus, 7);
    else memset(rows, 0, 7);
}

#endif
